package com.schoolagenda.service;

import com.schoolagenda.domain.entity.*;
import com.schoolagenda.domain.enums.*;
import com.schoolagenda.dto.note.NoteRequest;
import com.schoolagenda.infrastructure.storage.StorageService;
import com.schoolagenda.repository.*;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.interceptor.TransactionInterceptor;
import org.springframework.transaction.support.TransactionTemplate;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

class NoteUploadTransactionTest {
    NoteRepository notes;
    ImageRepository images;
    StorageService storage;
    JdbcTemplate jdbc;
    NoteService service;
    NoteRequest request;
    DataSourceTransactionManager transactionManager;

    @BeforeEach void setup() {
        var dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE test_notes(id BIGINT PRIMARY KEY)");
        jdbc.execute("CREATE TABLE test_images(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note_id BIGINT)");
        transactionManager = new DataSourceTransactionManager(dataSource);
        notes = mock(NoteRepository.class); images = mock(ImageRepository.class); storage = mock(StorageService.class);
        var users = mock(UserRepository.class); var students = mock(StudentRepository.class);
        User director = new User(); director.setId(1L); director.setName("Diretor"); director.setRole(new Role(RoleName.DIRECTOR));
        Student student = new Student(); student.setId(100L); student.setName("Aluno");
        when(users.findByEmailAndDeletedAtIsNull("diretor@escola.com")).thenReturn(Optional.of(director));
        when(students.findById(100L)).thenReturn(Optional.of(student));
        when(notes.save(any())).thenAnswer(invocation -> {
            Note note = invocation.getArgument(0); note.setId(900L);
            jdbc.update("INSERT INTO test_notes VALUES (900)"); return note;
        });
        when(images.save(any())).thenAnswer(invocation -> {
            Image image = invocation.getArgument(0);
            jdbc.update("INSERT INTO test_images(note_id) VALUES (?)", image.getNote().getId()); return image;
        });
        var target = new NoteService(notes, students, mock(TeacherRepository.class), mock(ResponsibleRepository.class),
                mock(ResponsibleStudentRepository.class), users, storage, images, mock(NoteReadRepository.class));
        var factory = new ProxyFactory(target); factory.setProxyTargetClass(true);
        factory.addAdvice(new TransactionInterceptor(transactionManager, new AnnotationTransactionAttributeSource()));
        service = (NoteService) factory.getProxy();
        request = new NoteRequest(); request.setStudentId(100L); request.setContent("Conteudo"); request.setType(NoteType.GENERAL);
    }
    private MockMultipartFile file(String name) {
        return new MockMultipartFile("images", name, "image/png", new byte[]{1, 2});
    }
    @Test void secondUploadFailureRollsBackDatabaseAndCleansFirstFile() {
        when(storage.upload(anyString(), any(), anyString())).thenReturn("first.png").thenThrow(new RuntimeException("Falha externa"));
        assertThrows(RuntimeException.class, () -> service.create(request, List.of(file("a.png"), file("b.png")), "diretor@escola.com"));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM test_notes", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM test_images", Integer.class));
        verify(storage).delete("first.png");
    }
    @Test void imagePersistenceFailureCleansUploadedFileAndRollsBackNote() {
        when(storage.upload(anyString(), any(), anyString())).thenReturn("first.png");
        doThrow(new RuntimeException("Falha do banco")).when(images).save(any());
        assertThrows(RuntimeException.class, () -> service.create(request, List.of(file("a.png")), "diretor@escola.com"));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM test_notes", Integer.class));
        verify(storage).delete("first.png");
    }
    @Test void successfulCreateReturnsAttachmentsAndDoesNotDeleteThem() {
        when(storage.upload(anyString(), any(), anyString())).thenReturn("first.png");
        var response = service.create(request, List.of(file("a.png")), "diretor@escola.com");
        assertEquals(1, response.getImages().size());
        assertEquals("first.png", response.getImages().get(0).getStorageKey());
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM test_notes", Integer.class));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM test_images", Integer.class));
        verify(storage, never()).delete(anyString());
    }
    @Test void enclosingTransactionRollbackCleansFilesEvenAfterCreateReturns() {
        when(storage.upload(anyString(), any(), anyString())).thenReturn("first.png");
        new TransactionTemplate(transactionManager).executeWithoutResult(status -> {
            service.create(request, List.of(file("a.png")), "diretor@escola.com");
            status.setRollbackOnly();
        });
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM test_notes", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM test_images", Integer.class));
        verify(storage).delete("first.png");
    }
    private Note prepareDeletion() {
        Note note = new Note(); note.setId(900L);
        Student student = new Student(); student.setId(100L); note.setStudent(student);
        Image image = new Image(); image.setStorageKey("existing.png"); note.setImages(List.of(image));
        when(notes.findById(900L)).thenReturn(Optional.of(note));
        doAnswer(invocation -> invocation.getArgument(0)).when(notes).save(any());
        return note;
    }
    @Test void rollbackOfDeletionKeepsExistingFiles() {
        prepareDeletion();
        new TransactionTemplate(transactionManager).executeWithoutResult(status -> {
            service.delete(900L, "diretor@escola.com");
            verify(storage, never()).delete(anyString());
            status.setRollbackOnly();
        });
        verify(storage, never()).delete(anyString());
    }
    @Test void committedDeletionCleansFilesOnlyAfterCommit() {
        Note note = prepareDeletion();
        new TransactionTemplate(transactionManager).executeWithoutResult(status -> {
            service.delete(900L, "diretor@escola.com");
            assertNotNull(note.getDeletedAt());
            verify(storage, never()).delete(anyString());
        });
        verify(storage).delete("existing.png");
    }

    @Test void cleanupFailureDoesNotReplaceUploadErrorOrStopOtherCleanup() {
        when(storage.upload(anyString(), any(), anyString())).thenReturn("first.png", "second.png")
                .thenThrow(new IllegalArgumentException("upload indisponivel"));
        doThrow(new IllegalStateException("limpeza indisponivel")).when(storage).delete("first.png");
        var error = assertThrows(RuntimeException.class, () -> service.create(request,
                List.of(file("a.png"), file("b.png"), file("c.png")), "diretor@escola.com"));
        assertInstanceOf(IllegalArgumentException.class, error.getCause());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM test_notes", Integer.class));
        verify(storage).delete("second.png");
    }
}
